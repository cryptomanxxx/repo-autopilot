// Regenerates worker/src/vendor/ext-apps.js from the MCP Apps SDK's prebuilt browser bundle, so the card
// can run the official App client with no build step and nothing loaded from other sites:
//   npm pack @modelcontextprotocol/ext-apps@1.7.5 && tar -xzf modelcontextprotocol-ext-apps-1.7.5.tgz
//   node scripts/vendor-ext-apps.mjs package
// The bundle's final export statement becomes a global, McpApps, so it can be inlined as a classic script.
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';

const dir=process.argv[2];
if(!dir) {console.error('Usage: node scripts/vendor-ext-apps.mjs <unpacked @modelcontextprotocol/ext-apps package>');process.exit(1);}
const {name,version,license}=JSON.parse(readFileSync(join(dir,'package.json'),'utf8'));
const bundle=readFileSync(join(dir,'dist/src/app-with-deps.js'),'utf8');
const exported=/export\{([^}]*)\};?\s*$/.exec(bundle);
if(!exported) throw new Error('The bundle no longer ends with one export statement.');
const names=exported[1].split(',').map(part=>part.trim().split(/\s+as\s+/)).map(([local,as])=>`${JSON.stringify(as||local)}:${local}`);
const script=`(()=>{${bundle.slice(0,exported.index)};globalThis.McpApps={${names.join(',')}};})();`;
if(/<\/script/i.test(script)) throw new Error('The bundle contains a closing script tag.');
writeFileSync(new URL('../worker/src/vendor/ext-apps.js',import.meta.url),`// Generated by scripts/vendor-ext-apps.mjs from ${name}@${version} (${license} license,
// https://github.com/modelcontextprotocol/ext-apps). Do not edit; regenerate instead.
export const EXT_APPS_VERSION=${JSON.stringify(version)};
export const EXT_APPS_SCRIPT=${JSON.stringify(script)};
`);
console.log(`Wrote ${name}@${version}: ${script.length} characters.`);
